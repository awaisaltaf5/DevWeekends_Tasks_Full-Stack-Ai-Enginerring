const express = require("express");
const User = require("../model/user");
const { upload } = require("../multer");
const { uploadBuffer, deleteAsset } = require("../config/cloudinary");
const templates = require("../utils/emailTemplates");
const ErrorHandler = require("../utils/ErrorHandler");
const jwt = require("jsonwebtoken");
const sendMail = require("../utils/sendMail");
const catchAsyncErrors = require("../middleware/catchAsyncErrors");
const sendToken = require("../utils/jwtToken");
const { OAuth2Client } = require("google-auth-library");
const { isAuthenticated, isAdmin } = require("../middleware/auth");

const router = express.Router();

router.post("/create-user", upload.single("file"), async (req, res, next) => {
  try {
    const { name, email, password } = req.body;
    const userEmail = await User.findOne({ email });

    if (userEmail) {
      return next(new ErrorHandler("User already exists", 400));
    }

    let avatar = undefined;
    if (req.file) {
      const result = await uploadBuffer(req.file.buffer, "vendora/avatars");
      avatar = result.secure_url;
    }

    const user = {
      name: name,
      email: email,
      password: password,
      avatar: avatar,
    };

    const activationToken = createActivationToken(user);

    const activationUrl = `${process.env.CLIENT_URL}/activation/${activationToken}`;

    // send email to user (fail-soft — email outages must not block registration)
    await sendMail({
      email: user.email,
      subject: "Activate your Vendora account",
      html: templates.userActivation({ name: user.name, activationUrl }),
      message: `Hello ${user.name}, please click on the link to activate your account: ${activationUrl}`,
    });
    res.status(201).json({
      success: true,
      message: `please check your email:- ${user.email} to activate your account!`,
    });
  } catch (err) {
    return next(new ErrorHandler(err.message, 400));
  }
});

// create activation token
const createActivationToken = (user) => {
  // why use create activatetoken?
  // to create a token for the user to activate their account  after they register
  return jwt.sign(user, process.env.ACTIVATION_SECRET, {
    expiresIn: "5m",
  });
};

// activate user account
router.post(
  "/activation",
  catchAsyncErrors(async (req, res, next) => {
    try {
      const { activation_token } = req.body;

      const newUser = jwt.verify(
        activation_token,
        process.env.ACTIVATION_SECRET
      );
      if (!newUser) {
        return next(new ErrorHandler("Invalid token", 400));
      }
      const { name, email, password, avatar } = newUser;

      let user = await User.findOne({ email });

      if (user) {
        return next(new ErrorHandler("User already exists", 400));
      }
      user = await User.create({
        name,
        email,
        avatar,
        password,
      });
      sendToken(user, 201, res);
    } catch (error) {
      // invalid/expired activation tokens are a client error → 400, not 500
      const isTokenError =
        error.name === "JsonWebTokenError" || error.name === "TokenExpiredError";
      const status = isTokenError ? 400 : 500;
      const message = isTokenError
        ? error.name === "TokenExpiredError"
          ? "Activation link has expired. Please register again."
          : "Invalid activation token."
        : error.message;
      return next(new ErrorHandler(message, status));
    }
  })
);

