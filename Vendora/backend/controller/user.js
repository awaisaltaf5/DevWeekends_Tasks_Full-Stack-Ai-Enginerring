// Google OAuth login / sign-up
router.post(
  "/google-login",
  catchAsyncErrors(async (req, res, next) => {
    try {
      const { credential } = req.body;
      if (!credential) {
        return next(new ErrorHandler("Google credential is required", 400));
      }

      const client = new OAuth2Client(process.env.GOOGLE_CLIENT_ID);
      const ticket = await client.verifyIdToken({
        idToken: credential,
        audience: process.env.GOOGLE_CLIENT_ID,
      });
      const payload = ticket.getPayload();

      if (!payload || !payload.email) {
        return next(new ErrorHandler("Invalid Google token", 400));
      }

      let user = await User.findOne({ email: payload.email });

      if (!user) {
        user = await User.create({
          name: payload.name || payload.email.split("@")[0],
          email: payload.email,
          avatar: payload.picture,
          password: jwt.sign({ g: payload.sub }, process.env.JWT_SECRET), // random unusable password
        });
      }

      sendToken(user, 200, res);
    } catch (error) {
      return next(new ErrorHandler("Google authentication failed", 400));
    }
  })
);

// update user addresses
router.put(
  "/update-user-addresses",
  isAuthenticated,
  catchAsyncErrors(async (req, res, next) => {
    try {
      const user = await User.findById(req.user.id);

      const sameTypeAddress = user.addresses.find(
        (address) => address.addressType === req.body.addressType
      );
      if (sameTypeAddress) {
        return next(
          new ErrorHandler(`${req.body.addressType} address already exists`)
        );
      }

      const existsAddress = user.addresses.find(
        (address) => address._id === req.body._id
      );

      if (existsAddress) {
        Object.assign(existsAddress, req.body);
      } else {
        // add the new address to the array
        user.addresses.push(req.body);
      }

      await user.save();

      res.status(200).json({
        success: true,
        user,
      });
    } catch (error) {
      return next(new ErrorHandler(error.message, 500));
    }
  })
);

